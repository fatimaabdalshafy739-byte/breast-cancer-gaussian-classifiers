import warnings; warnings.filterwarnings("ignore")
import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm
from sklearn.datasets import load_breast_cancer
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis, QuadraticDiscriminantAnalysis
from sklearn.naive_bayes import GaussianNB

data = load_breast_cancer()
X, y, names = data.data, data.target, data.feature_names
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=0, stratify=y)
print(X_train.shape, "training samples,", X_test.shape[0], "test samples")
print("class counts in training:", np.bincount(y_train), "(0 = malignant, 1 = benign)")

"""### Task 1 — One feature, one normal curve per class
Use the first feature, `mean radius` (column 0), of the **training** data. For each class, estimate the mean and the standard deviation by
maximum likelihood (divide by $n$). Also compute the two priors (the share of each class in the training data).
"""

# Mean radius (column 0) for each class: 0 = malignant, 1 = benign
MEAN_RADIUS_IDX = 0
MALIGNANT, BENIGN = 0, 1

radius_malignant = X_train[y_train == MALIGNANT, MEAN_RADIUS_IDX]
radius_benign = X_train[y_train == BENIGN, MEAN_RADIUS_IDX]

# Class means
radius_mean_malignant = np.mean(radius_malignant)
radius_mean_benign = np.mean(radius_benign)

# Class standard deviations using MLE (divide by n, not n-1)
radius_std_malignant = np.sqrt(np.mean((radius_malignant - radius_mean_malignant) ** 2))
radius_std_benign = np.sqrt(np.mean((radius_benign - radius_mean_benign) ** 2))

# Class priors
prior_malignant = len(radius_malignant) / len(y_train)
prior_benign = len(radius_benign) / len(y_train)

print("Malignant Mean:", radius_mean_malignant)
print("Benign Mean:", radius_mean_benign)

print("Malignant Std:", radius_std_malignant)
print("Benign Std:", radius_std_benign)

print("Malignant Prior:", prior_malignant)
print("Benign Prior:", prior_benign)

"""**Explain in your own words (2–3 sentences):** which class has the larger radius, and which class has the larger spread?
What does the different spread mean for the shape of the boundary (Notes §5.4.1)?

*Your answer:*
Malignant samples have a larger mean radius than benign samples. They also have a larger standard deviation, which means their radius values are more spread out. Because the two classes have different spreads, the decision boundary may be curved instead of a single linear boundary.

### Task 2 — Same spread or own spread?
(a) Assume both classes have the **same** spread: the pooled standard deviation $\sqrt{\frac{1}{n}\sum_c\sum_{k\in c}(x_k-\hat\mu_c)^2}$.
Use the threshold formula of the Notes (benign has the **smaller** mean, so decide benign **below** the threshold).
(b) Now give each class **its own** spread. Use the score $g_c(x)=-\frac{(x-\mu_c)^2}{2\sigma_c^2}-\ln\sigma_c+\ln P(\omega_c)$ on a grid from 0 to 40 and
find **all** the points where the decision changes. (c) Count the correct test decisions of both rules.
"""

# (a) Pooled standard deviation (same spread for both classes)
radius_pooled_std = np.sqrt(
    (np.sum((radius_malignant - radius_mean_malignant) ** 2) +
     np.sum((radius_benign - radius_mean_benign) ** 2)) / len(y_train)
)

# Decision threshold between the two classes (equal-spread rule)
equal_spread_threshold = (radius_mean_malignant + radius_mean_benign) / 2 + (
    radius_pooled_std ** 2 / (radius_mean_malignant - radius_mean_benign)
) * np.log(prior_benign / prior_malignant)

print("Pooled Standard Deviation:", radius_pooled_std)
print("Decision Threshold:", equal_spread_threshold)


# (b) Gaussian log-score for each class (each class has its own spread)
def gaussian_log_score(x, class_mean, class_std, class_prior):
    return (-(x - class_mean) ** 2 / (2 * class_std ** 2)
            - np.log(class_std) + np.log(class_prior))


# Grid of radius values from 0 to 40
radius_grid = np.linspace(0, 40, 40001)

grid_score_malignant = gaussian_log_score(
    radius_grid, radius_mean_malignant, radius_std_malignant, prior_malignant)
grid_score_benign = gaussian_log_score(
    radius_grid, radius_mean_benign, radius_std_benign, prior_benign)

# Find where the predicted class flips
predicts_benign = grid_score_benign > grid_score_malignant
boundary_idx = np.where(predicts_benign[1:] != predicts_benign[:-1])[0]

print("Decision boundaries:")
for idx in boundary_idx:
    print(radius_grid[idx], radius_grid[idx + 1])


# (c) Test both rules on the test set
test_radius = X_test[:, MEAN_RADIUS_IDX]

# Rule 1: same spread (single threshold)
pred_equal_spread = np.where(test_radius < equal_spread_threshold, BENIGN, MALIGNANT)
n_correct_equal_spread = np.sum(pred_equal_spread == y_test)

# Rule 2: own spread (compare class scores)
test_score_malignant = gaussian_log_score(
    test_radius, radius_mean_malignant, radius_std_malignant, prior_malignant)
test_score_benign = gaussian_log_score(
    test_radius, radius_mean_benign, radius_std_benign, prior_benign)

pred_own_spread = np.where(test_score_benign > test_score_malignant, BENIGN, MALIGNANT)
n_correct_own_spread = np.sum(pred_own_spread == y_test)

print("Correct decisions (same spread):", n_correct_equal_spread)
print("Correct decisions (own spread):", n_correct_own_spread)

"""**Explain in your own words (2–3 sentences):** in (b) you find a boundary at a **very small** radius. Below it, the rule says *malignant*.
Why does this happen, although malignant samples usually have a *large* radius? (Notes, Worked example 5.5.)

*Your answer:*

Although malignant samples usually have a larger radius, their standard deviation is also larger. This makes their normal distribution wider, so it can have a higher probability density in the very small radius region. Therefore, the model may classify very small values as malignant.

### Task 3 — Two features: the covariance matrices
Use `mean radius` and `mean texture` (columns 0 and 1). For each class print the mean vector, the covariance matrix (`bias=True`) and the correlation.
Then train LDA, QDA and `GaussianNB` on these two columns and count the correct test decisions.
"""

# Use only mean radius and mean texture (columns 0 and 1)
X_train_radius_texture = X_train[:, :2]
X_test_radius_texture = X_test[:, :2]

# Class labels: 0 = malignant, 1 = benign
MALIGNANT, BENIGN = 0, 1
class_names = {MALIGNANT: "Malignant", BENIGN: "Benign"}

for class_label in [MALIGNANT, BENIGN]:
    X_class = X_train_radius_texture[y_train == class_label]

    class_mean_vector = X_class.mean(axis=0)
    class_cov_matrix = np.cov(X_class, rowvar=False, bias=True)    # bias=True -> divide by n
    radius_texture_corr = np.corrcoef(X_class, rowvar=False)[0, 1]  # correlation between the two features

    print(f"--- {class_names[class_label]} ---")
    print("Mean vector:", class_mean_vector)
    print("Covariance matrix:\n", class_cov_matrix)
    print("Correlation (radius, texture):", radius_texture_corr)
    print()

# Train the three models
lda_model = LinearDiscriminantAnalysis().fit(X_train_radius_texture, y_train)
qda_model = QuadraticDiscriminantAnalysis().fit(X_train_radius_texture, y_train)
gnb_model = GaussianNB().fit(X_train_radius_texture, y_train)

# Count correct test decisions
classifiers = {"LDA": lda_model, "QDA": qda_model, "GaussianNB": gnb_model}

for clf_name, classifier in classifiers.items():
    y_pred = classifier.predict(X_test_radius_texture)
    n_correct = np.sum(y_pred == y_test)
    print(f"{clf_name}: {n_correct} correct out of {len(y_test)}")

